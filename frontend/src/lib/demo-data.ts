export function computeMetrics(batches: Batch[]): DashboardMetrics {
  const totalBatches = batches.length;
  const evidenceSupportedKg = batches.reduce(
    (acc, b) => acc + (b.status === "SUPPORTED" ? b.massBalance.evidenceSupportedKg : 0),
    0
  );
  const batchesRequiringReview = batches.filter(
    (b) => b.status === "REVIEW_REQUIRED" || b.status === "REJECTED"
  ).length;
  const estimatedRecoveryValueUsd = batches.reduce(
    (acc, b) => acc + (b.status === "SUPPORTED" ? b.materialEstimate.netEstimatedRecoveryValueUsd : 0),
    0
  );
  const totalClaimedKg = batches.reduce((acc, b) => acc + b.claimedQuantity, 0);
  const supportedBatchesCount = batches.filter((b) => b.status === "SUPPORTED").length;
  const rejectedBatchesCount = batches.filter((b) => b.status === "REJECTED").length;

  return {
    totalBatches,
    evidenceSupportedKg,
    batchesRequiringReview,
    estimatedRecoveryValueUsd,
    totalClaimedKg,
    supportedBatchesCount,
    rejectedBatchesCount,
  };
}
